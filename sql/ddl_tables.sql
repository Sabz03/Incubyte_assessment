CREATE WAREHOUSE IF NOT EXISTS SKYPOINTS_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

USE WAREHOUSE SKYPOINTS_WH;

CREATE DATABASE IF NOT EXISTS SKYPOINTS_DB;
USE DATABASE SKYPOINTS_DB;

CREATE SCHEMA IF NOT EXISTS BRONZE;
CREATE SCHEMA IF NOT EXISTS SILVER;
CREATE SCHEMA IF NOT EXISTS GOLD;
CREATE SCHEMA IF NOT EXISTS AUDIT;

-- Central operational audit table tracking runs by BATCH_ID
CREATE TABLE IF NOT EXISTS AUDIT.PIPELINE_AUDIT (
    AUDIT_ID         VARCHAR(64) DEFAULT UUID_STRING(),
    BATCH_ID         VARCHAR(64) NOT NULL DEFAULT UUID_STRING(),
    STAGE            VARCHAR(32) NOT NULL, -- BRONZE_INGEST | RAW_TO_STG | STG_TO_GOLD
    STATUS           VARCHAR(16) NOT NULL, -- RUNNING | SUCCESS | FAILED
    ROWS_READ        NUMBER DEFAULT 0,
    ROWS_WRITTEN     NUMBER DEFAULT 0,
    ROWS_QUARANTINED NUMBER DEFAULT 0,
    ERROR_MESSAGE    VARCHAR(4000),
    STARTED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    ENDED_AT         TIMESTAMP_NTZ,
    BIW_LOAD_DATE    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- BRONZE: Append-only raw landing for 11-column member feed
CREATE TABLE IF NOT EXISTS BRONZE.RAW_MEMBER_PROFILES (
    MEMBER_NAME      VARCHAR(255),
    MEMBER_ID        VARCHAR(18),
    ENROLLMENT_DATE  VARCHAR(20),
    LAST_FLIGHT_DATE VARCHAR(20),
    TIER_CODE        VARCHAR(5),
    AGENT_NAME       VARCHAR(255),
    STATE            VARCHAR(5),
    COUNTRY          VARCHAR(5),
    POST_CODE        VARCHAR(20),
    DATE_OF_BIRTH    VARCHAR(20),
    ACTIVE_MEMBER    VARCHAR(1),
    SOURCE_FILE      VARCHAR(255),
    BATCH_ID         VARCHAR(64) NOT NULL DEFAULT UUID_STRING(),
    BIW_LOAD_DATE    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- BRONZE: Bad / invalid member records quarantined in Bronze
CREATE TABLE IF NOT EXISTS BRONZE.QUARANTINE_MEMBER_PROFILES (
    MEMBER_NAME      VARCHAR(255),
    MEMBER_ID        VARCHAR(18),
    ENROLLMENT_DATE  VARCHAR(20),
    LAST_FLIGHT_DATE VARCHAR(20),
    TIER_CODE        VARCHAR(5),
    AGENT_NAME       VARCHAR(255),
    STATE            VARCHAR(5),
    COUNTRY          VARCHAR(5),
    POST_CODE        VARCHAR(20),
    DATE_OF_BIRTH    VARCHAR(20),
    ACTIVE_MEMBER    VARCHAR(1),
    REJECT_REASON    VARCHAR(500),
    SOURCE_FILE      VARCHAR(255),
    BATCH_ID         VARCHAR(64) NOT NULL,
    BIW_LOAD_DATE    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- BRONZE: Append-only raw JSON redemption payload landing
CREATE TABLE IF NOT EXISTS BRONZE.RAW_REDEMPTION_JSON (
    PAYLOAD          VARIANT,
    SOURCE_FILE      VARCHAR(255),
    BATCH_ID         VARCHAR(64) NOT NULL DEFAULT UUID_STRING(),
    BIW_LOAD_DATE    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- BRONZE: Flattened valid JSON redemption records in Bronze
CREATE TABLE IF NOT EXISTS BRONZE.REDEMPTION_JSON_FLAT (
    TXN_ID           VARCHAR(64),
    MEMBER_ID        VARCHAR(64),
    FEED_DATE_RAW    VARCHAR(20),
    TXN_DATE_RAW     VARCHAR(20),
    PARTNER          VARCHAR(100),
    MILES_RAW        VARCHAR(50),
    STATUS           VARCHAR(32),
    SOURCE_FILE      VARCHAR(255),
    BATCH_ID         VARCHAR(64) NOT NULL,
    BIW_LOAD_DATE    TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- BRONZE: Bad / malformed JSON payloads or invalid redemption items kept in Bronze
