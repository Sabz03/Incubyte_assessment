--GOLD_LAYER
CREATE OR REPLACE VIEW GOLD.MEMBER_LOYALTY_SUMMARY AS
WITH active_members AS (
    SELECT
        MEMBER_NAME,
        MEMBER_ID,
        COUNTRY,
        POST_CODE,
        TIER_CODE,
        ACTIVE_MEMBER,
        AGE,
        STALE_MEMBER,
        IS_ACTIVE,
        BATCH_ID,
        BIW_LOAD_DATE
    FROM SILVER.TABLE_INDIA
    WHERE IS_ACTIVE = 'Y'

    UNION ALL

    SELECT
        MEMBER_NAME,
        MEMBER_ID,
        COUNTRY,
        POST_CODE,
        TIER_CODE,
        ACTIVE_MEMBER,
        AGE,
        STALE_MEMBER,
        IS_ACTIVE,
        BATCH_ID,
        BIW_LOAD_DATE
    FROM SILVER.TABLE_USA
    WHERE IS_ACTIVE = 'Y'

    UNION ALL

    SELECT
        MEMBER_NAME,
        MEMBER_ID,
        COUNTRY,
        POST_CODE,
        TIER_CODE,
        ACTIVE_MEMBER,
        AGE,
        STALE_MEMBER,
        IS_ACTIVE,
        BATCH_ID,
        BIW_LOAD_DATE
    FROM SILVER.TABLE_AUS
    WHERE IS_ACTIVE = 'Y'
),
redemption_agg AS (
    SELECT
        MEMBER_ID,
        COUNT_IF(UPPER(TRIM(STATUS)) = 'COMPLETED') AS TOTAL_REDEMPTIONS,
        COALESCE(SUM(IFF(UPPER(TRIM(STATUS)) = 'COMPLETED', MILES_REDEEMED, 0)), 0)::NUMBER(18, 2) AS TOTAL_MILES_REDEEMED,
        COALESCE(SUM(IFF(UPPER(TRIM(STATUS)) = 'PENDING',   MILES_REDEEMED, 0)), 0)::NUMBER(18, 2) AS PENDING_MILES,
        COALESCE(SUM(IFF(UPPER(TRIM(STATUS)) = 'REVERSED',  MILES_REDEEMED, 0)), 0)::NUMBER(18, 2) AS REVERSED_MILES
    FROM SILVER.MEMBER_REDEMPTIONS
    GROUP BY MEMBER_ID
)
SELECT
    m.MEMBER_NAME,
    m.MEMBER_ID,
    m.COUNTRY,
    m.POST_CODE,
    m.TIER_CODE,
    m.ACTIVE_MEMBER,
    m.AGE,
    m.STALE_MEMBER,
    m.IS_ACTIVE,
    COALESCE(r.TOTAL_REDEMPTIONS, 0)::NUMBER(18, 0)    AS TOTAL_REDEMPTIONS,
    COALESCE(r.TOTAL_MILES_REDEEMED, 0)::NUMBER(18, 2) AS TOTAL_MILES_REDEEMED,
    COALESCE(r.PENDING_MILES, 0)::NUMBER(18, 2)        AS PENDING_MILES,
    COALESCE(r.REVERSED_MILES, 0)::NUMBER(18, 2)       AS REVERSED_MILES,
    m.BATCH_ID,
    m.BIW_LOAD_DATE
FROM active_members m
LEFT JOIN redemption_agg r
    ON m.MEMBER_ID = r.MEMBER_ID;